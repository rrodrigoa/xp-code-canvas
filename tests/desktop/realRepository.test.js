const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {VSBrowser,Workbench,EditorView,WebView,By,Key}=require('vscode-extension-tester');
const repository=process.env.XP_REAL_REPO;
const evidenceDirectory=process.env.XP_EVIDENCE_DIR||'test-results/real-repository';
const git=(...args)=>execFileSync('git',args,{cwd:repository,encoding:'utf8',windowsHide:true}).trim();
describe('Installed V6 against real Flask history and source',()=>{
 let view,driver;
 const find=selector=>driver.findElement(By.css(selector));
 const waitText=(selector,text)=>driver.wait(async()=>(await find(selector).getText()).includes(text),60000,`${selector} must contain ${text}`);
 const screenshot=async name=>{fs.mkdirSync(evidenceDirectory,{recursive:true});fs.writeFileSync(path.join(evidenceDirectory,`${name}.png`),await driver.takeScreenshot(),'base64');};
 before(async()=>{
  assert.ok(repository,'Use the real-repository runner');driver=VSBrowser.instance.driver;
  await new Workbench().executeCommand('Python UML Canvas: Open UML Canvas');
  await driver.wait(async()=>(await new EditorView().getOpenEditorTitles()).includes('Python UML Canvas'),30000);
  view=new WebView();await view.switchToFrame(30000);
  await driver.wait(async()=>(await driver.findElements(By.css('.uml-node'))).length>0,90000,'Flask graph must render');
 });
 after(async()=>{if(view)await view.switchBack();});
 it('shows real commit subjects, authors, branch topology and selected baseline',async()=>{
  await find('button[aria-label="Git history"]').click();
  const modes=await find('[aria-label="Git information mode"]');
  await modes.findElement(By.xpath('.//button[normalize-space()="History"]')).click();
  await driver.wait(async()=>(await driver.findElements(By.css('.git-commit-row'))).length===100,30000);
  const row=await find('.git-commit-row');
  assert.ok((await row.getText()).includes(git('log','-1','--format=%s')));
  assert.ok((await row.getText()).includes(git('log','-1','--format=%an')));
  assert.equal((await driver.findElements(By.css('.git-lane-plot circle'))).length,100);
  await row.click();assert.equal(await row.getAttribute('aria-current'),'true');
  await screenshot('flask-history');
  await find('.git-drawer-footer .button-primary').click();
  await waitText('.status-message',`baseline ${git('rev-parse','HEAD')}`);
  await find('button[aria-label="Close Git history"]').click();
 });
 it('loads real source and per-line blame with inspectable commit provenance',async()=>{
  const input=await find('[aria-label="Find Python symbol"]');await input.sendKeys('Config');
  await driver.wait(async()=>(await driver.findElements(By.css('.symbol-search-results button'))).length>0,10000);
  await input.sendKeys(Key.ENTER);
  await driver.wait(async()=>(await driver.findElements(By.css('.uml-node.selected.uml-class'))).length===1,15000);
  await find('.uml-node.selected button[aria-label^="More actions"]').click();
  const expansion=await find('.node-menu button[role="menuitem"]');
  if((await expansion.getText()).includes('Expand'))await expansion.click();
  else await find('.uml-node.selected button[aria-label^="More actions"]').click();
  await driver.wait(async()=>(await driver.findElements(By.css('.uml-node.selected .source-code-row'))).length>20,20000);
  await find('.uml-node.selected button[aria-label^="More actions"]').click();
  await driver.findElement(By.xpath('//button[@role="menuitem" and contains(.,"Inspect Git blame")]')).click();
  await driver.wait(async()=>(await driver.findElements(By.css('.uml-node.selected .source-blame-mark.has-blame'))).length>10,20000,'Real line blame must appear in the code view');
  const graph=await find('main'),bounds=await graph.getRect();
  // Ordinary wheel over empty canvas pans the expanded code card into view.
  await driver.actions().scroll(-Math.floor(bounds.width*.35),0,0,700,graph).perform();
  await find('.uml-node.selected .source-blame-mark.has-blame').click();
  const card=await find('.source-attribution-card');
  const text=await card.getText();
  const commit=(await card.findElement(By.css('code')).getText()).trim();
  assert.match(commit,/^[a-f0-9]{10}$/,'Commit provenance must be visibly readable');
  assert.ok(text.includes(git('show','-s','--format=%an',commit)));
  assert.ok(text.includes(git('show','-s','--format=%s',commit)));
  assert.ok((await find('.uml-node.selected .source-preview').getText()).includes('class Config'));
  await screenshot('flask-blame-code');
  await card.findElement(By.css('.source-compare-commit')).click();
  await waitText('.status-message','baseline');
  await screenshot('flask-blame-comparison');
 });
 it('compares an actual code-changing revision and retains real-source Sankey and navigation',async()=>{
  await find('button[aria-label="Advanced graph, Git, and trace controls"]').click();
  const commit=git('log','-1','--format=%H','--','src/flask/config.py');
  const baseline=git('rev-parse',`${commit}^`);
  const revision=await find('[aria-label="Git revision or INDEX"]');await revision.sendKeys(Key.CONTROL,'a',Key.NULL,baseline);
  await find('.button-compare').click();await waitText('.status-message',`baseline ${baseline}`);
  await screenshot('flask-semantic-comparison');
  const search=await find('[aria-label="Find Python symbol"]');await search.sendKeys('flask.app');
  const moduleOption=By.xpath('//button[@role="option"][.//strong[normalize-space()="flask.app"]]');
  await driver.wait(async()=>(await driver.findElements(moduleOption)).length===1,10000,'Find the exact flask.app module');
  await driver.findElement(moduleOption).click();
  await driver.wait(async()=>(await driver.findElements(By.css('.uml-node.selected[data-testid="symbol-module"]'))).length===1,15000,'Reveal the selected Flask app module');
  await driver.findElement(By.xpath('//button[normalize-space()="Flow"]')).click();
  await driver.wait(async()=>(await driver.findElements(By.css('.sankey-lens'))).length===1,15000);
  await find('[aria-label="Sankey relationship type"] option[value="imports"]').click();
  await driver.wait(async()=>(await driver.findElements(By.css('.flow-ribbon'))).length>0,10000,'Real imports must render nonempty Sankey ribbons');
  await screenshot('flask-sankey');
  await find('button[aria-label="Return to UML diagram"]').click();
  await search.sendKeys('Config');
  const configOption=By.xpath('//button[@role="option"][.//strong[normalize-space()="flask.config.Config"]]');
  await driver.wait(async()=>(await driver.findElements(configOption)).length===1,10000,'Find the exact Config class again');
  await driver.findElement(configOption).click();
  await waitText('.inspector h2','flask.config.Config');
  await find('.inspector-edit').click();
  await view.switchBack();
  await driver.wait(async()=>(await new EditorView().getOpenEditorTitles()).includes('config.py'),15000,'Native config.py editor must open');
  await new Workbench().executeCommand('Python UML Canvas: Return to UML Canvas');
  await driver.wait(async()=>(await new EditorView().getOpenEditorTitles()).includes('Python UML Canvas'),15000,'Return to the real-source canvas');
  await view.switchToFrame(15000);
 });
});
